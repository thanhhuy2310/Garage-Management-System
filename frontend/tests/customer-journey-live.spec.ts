import {test,expect} from "@playwright/test";
import {readFileSync} from "node:fs";
import {randomUUID} from "node:crypto";
const file=process.env.GARAGE_VERIFY_CREDENTIALS;
test.skip(!file,"Requires the dedicated verification API and SQL Server.");
test("customer adds a car inside booking, edits contact details and follows their notification",async({page,request})=>{
  const config=JSON.parse(readFileSync(file!,"utf8").replace(/^\uFEFF/,""));
  expect(config.database).toMatch(/^QuanLyGaraOTo_Verify_[0-9]{8}$/);
  expect(config.apiUrl).toMatch(/^http:\/\/(localhost|127\.0\.0\.1):8088\/api$/);
  const suffix=Date.now().toString().slice(-8),username="minhchau_"+suffix,password=randomUUID();
  const registration=await request.post("/api/auth/register",{data:{username,password,phone:"09"+suffix,fullName:"Trần Minh Châu",email:username+"@example.invalid"}});
  expect(registration.status()).toBe(201);
  const token=(await registration.json()).data.accessToken;
  await page.setViewportSize({width:390,height:844});
  await page.goto("/login");await page.getByLabel("Tên đăng nhập",{exact:true}).fill(username);await page.getByLabel("Mật khẩu",{exact:true}).fill(password);
  await page.getByRole("button",{name:"Đăng nhập",exact:true}).click();
  await page.getByRole("button",{name:"Đặt lịch ngay"}).click();
  const dialog=page.getByRole("dialog");
  await dialog.getByRole("button",{name:"Thêm xe ngay"}).click();
  const plate="51C-"+suffix.slice(-5);
  await dialog.getByLabel("Biển số xe *").fill(plate);
  await dialog.getByRole("button",{name:"Thêm xe",exact:true}).click();
  await expect(dialog.getByLabel("Xe",{exact:true})).not.toHaveValue("");
  const day=new Date(Date.now()+86400000*(18+Number(suffix.slice(-1)))).toISOString().slice(0,10);
  await dialog.getByLabel("Ngày hẹn",{exact:true}).fill(day);
  const grid=dialog.getByRole("group",{name:"Giờ hẹn (giờ Việt Nam)"});
  await expect(grid.getByRole("button")).toHaveCount(22);
  await grid.getByRole("button",{name:/Còn/}).first().click();
  const saved=page.waitForResponse(r=>r.url().endsWith("/api/appointments")&&r.request().method()==="POST");
  await dialog.getByRole("button",{name:"Lưu lịch hẹn"}).click();
  const response=await saved;expect(response.status()).toBe(201);const id=(await response.json()).data.id;
  await page.goto("/customer/profile");await page.getByLabel("Địa chỉ",{exact:true}).fill("Quận 3");
  const updated=page.waitForResponse(r=>r.url().endsWith("/api/customer/profile")&&r.request().method()==="PUT");
  await page.getByRole("button",{name:"Lưu thông tin liên hệ"}).click();expect((await updated).status()).toBe(200);
  await page.reload();await expect(page.getByLabel("Địa chỉ",{exact:true})).toHaveValue("Quận 3");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.goto("/customer/notifications");
  const read=page.waitForResponse(r=>r.request().method()!=="GET"&&r.url().includes("/notifications/"));
  await page.locator("li button").first().click();expect((await read).ok()).toBeTruthy();
  await expect(page).toHaveURL(new RegExp("/customer/appointments\\?id="+id+"$"));
  await expect(page.getByRole("heading",{name:"LH"+id+" · "+plate,exact:true})).toBeVisible();
  const cancel=await request.patch("/api/appointments/"+id+"/cancel",{headers:{Authorization:"Bearer "+token},data:{version:0,reason:"Hoàn tất kiểm thử"}});
  expect(cancel.ok()).toBeTruthy();
});
