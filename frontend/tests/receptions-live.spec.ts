import {test,expect,type Page} from "@playwright/test";
import {readFileSync} from "node:fs";
import {execFileSync} from "node:child_process";
const path=process.env.GARAGE_VERIFY_CREDENTIALS;
const f=path?JSON.parse(readFileSync(path,"utf8").replace(/^\uFEFF/,"")):null;
test.skip(!f,"Requires an isolated SQL Server verification fixture.");
function sql(query:string){
  if(!/^QuanLyGaraOTo_Verify_\d{8}$/.test(f.database))throw new Error("Not a verification database");
  return execFileSync("sqlcmd",["-S","localhost","-E","-C","-I","-d",f.database,"-h","-1","-W","-b","-Q","SET NOCOUNT ON; "+query],{encoding:"utf8"}).trim();
}
async function login(page:Page){await page.goto("/login");await page.getByLabel("Tên đăng nhập",{exact:true}).fill(f.manager.username);await page.getByLabel("Mật khẩu",{exact:true}).fill(f.manager.password);await page.getByRole("button",{name:"Đăng nhập",exact:true}).click();await expect(page).not.toHaveURL(/\/login$/);}
test("reception Web creates customer and vehicle, persists walk-in, updates and creates linked repair",async({page})=>{
  await login(page);await page.goto("/admin/reception");
  await expect(page.getByText(/MOCK_ONLY/)).toHaveCount(0);
  await page.getByRole("button",{name:"Thêm khách hàng mới",exact:true}).click();
  const customerDialog=page.getByRole("dialog");
  await customerDialog.getByLabel("Họ tên",{exact:true}).fill("Nguyễn Hoàng Nam");
  await customerDialog.getByLabel("Số điện thoại",{exact:true}).fill("09"+Date.now().toString().slice(-8));
  await customerDialog.getByRole("button",{name:"Lưu khách hàng",exact:true}).click();
  await expect(customerDialog).toHaveCount(0);
  await page.getByRole("button",{name:"Tiếp theo",exact:true}).click();
  await page.getByRole("button",{name:"Thêm xe cho khách",exact:true}).click();
  const vehicleDialog=page.getByRole("dialog");
  const plate="51A-"+Date.now().toString().slice(-5);
  await vehicleDialog.getByLabel("Biển số xe *",{exact:true}).fill(plate);
  await vehicleDialog.getByLabel("Hãng xe",{exact:true}).fill("Toyota");
  await vehicleDialog.getByLabel("Dòng xe",{exact:true}).fill("Vios");
  await vehicleDialog.getByLabel("Số km",{exact:true}).fill("25000");
  await vehicleDialog.getByRole("button",{name:"Thêm xe",exact:true}).click();
  await expect(vehicleDialog).toHaveCount(0);
  await page.getByLabel("Số km hiện tại",{exact:true}).fill("25100");
  await page.getByRole("button",{name:"Tiếp theo",exact:true}).click();
  await expect(page.getByLabel("Lịch hẹn liên quan")).toHaveValue("");
  await page.getByLabel("Yêu cầu của khách hàng",{exact:true}).fill("Kiểm tra hệ thống phanh");
  await page.getByRole("button",{name:"Tiếp theo",exact:true}).click();
  await page.getByLabel("Tình trạng xe ban đầu",{exact:true}).fill("Phanh có tiếng kêu; ngoại thất nguyên vẹn");
  await page.getByRole("button",{name:"Tiếp theo",exact:true}).click();
  const created=page.waitForResponse(r=>r.request().method()==="POST"&&r.url().endsWith("/api/receptions"));
  await page.getByRole("button",{name:"Lập phiếu tiếp nhận",exact:true}).click();
  const response=await created;expect(response.status()).toBe(201);const receipt=(await response.json()).data;
  expect(receipt.appointmentId).toBeNull();
  expect(sql("SELECT CONCAT(SoKmTiepNhan,':',PhienBan) FROM PhieuTiepNhan WHERE MaTiepNhan="+Number(receipt.id))).toBe("25100:0");
  await page.reload();
  await page.getByRole("button").filter({hasText:`TN${receipt.id} · ${plate}`}).click();
  await expect(page.getByRole("heading",{name:`Phiếu tiếp nhận TN${receipt.id}`,exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Cập nhật tiếp nhận",exact:true}).click();
  await page.getByLabel("Số km hiện tại",{exact:true}).fill("25200");
  for(let step=0;step<3;step++)await page.getByRole("button",{name:"Tiếp theo",exact:true}).click();
  await page.getByRole("button",{name:"Lưu cập nhật",exact:true}).click();
  await expect(page.getByRole("button",{name:"Cập nhật tiếp nhận",exact:true})).toBeVisible();
  expect(sql("SELECT CONCAT(SoKmTiepNhan,':',PhienBan) FROM PhieuTiepNhan WHERE MaTiepNhan="+Number(receipt.id))).toBe("25200:1");
  await page.getByRole("button",{name:"Lập phiếu sửa chữa",exact:true}).click();
  const repairDialog=page.getByRole("dialog");
  await repairDialog.getByLabel("Kiểm tra hệ thống phanh",{exact:true}).check();
  await repairDialog.getByRole("button",{name:"Tạo phiếu sửa chữa",exact:true}).click();
  await expect(repairDialog).toHaveCount(0);
  const repairId=Number(sql("SELECT MaPhieuSuaChua FROM PhieuSuaChua WHERE MaTiepNhan="+Number(receipt.id)));
  expect(repairId).toBeGreaterThan(0);
  await page.reload();await page.getByRole("button").filter({hasText:`TN${receipt.id} · ${plate}`}).click();
  await expect(page.getByText(`Đã lập phiếu sửa chữa PSC${repairId}`,{exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Cập nhật tiếp nhận",exact:true})).toHaveCount(0);
  await page.getByRole("link",{name:"Mở quản lý sửa chữa",exact:true}).click();
  await expect(page).toHaveURL(/\/admin\/repair$/);
  await expect(page.getByText(plate,{exact:true}).first()).toBeVisible();
});
