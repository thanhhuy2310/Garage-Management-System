import {test,expect} from "@playwright/test";
import {readFileSync,writeFileSync} from "node:fs";
import {execFileSync} from "node:child_process";
const file=process.env.GARAGE_VERIFY_CREDENTIALS;
const config=file?JSON.parse(readFileSync(file,"utf8").replace(/^\uFEFF/,"")):null;
test.skip(!config,"Requires the separate SQL verification database and staff credentials.");
test("claim and private evidence persist after browser reload",async({page,browser,request})=>{
  test.setTimeout(90000);
  if(!/^QuanLyGaraOTo_Verify_[0-9]{8}$/.test(config.database))throw Error("Expected verification database");
  const sql=(query:string)=>execFileSync("sqlcmd",["-S","localhost","-E","-C","-I","-d",config.database,"-b","-W","-h","-1","-Q","SET NOCOUNT ON; "+query],{encoding:"utf8"}).trim();
  const suffix=Date.now().toString().slice(-9), plate="51B-"+suffix;
  const login=async(account:{username:string,password:string})=>{
    const r=await request.post("/api/auth/login",{data:{username:account.username,password:account.password}});
    expect(r.status()).toBe(200);return (await r.json()).data;
  };
  const customer=await login(config.customer),staff=await login(config.manager);
  const call=async(method:string,url:string,data?:unknown)=>{
    const r=await request.fetch("/api"+url,{method,headers:{Authorization:"Bearer "+staff.accessToken},data});
    expect(r.ok(),method+" "+url+" HTTP "+r.status()).toBeTruthy();return (await r.json()).data;
  };
  const owner=(await call("GET","/customers/"+customer.account.customerId)).fullName;
  const cid=Number(customer.account.customerId);expect(Number.isSafeInteger(cid)).toBeTruthy();
  const vehicle=sql("BEGIN TRAN; INSERT Xe(MaKhachHang,BienSo) VALUES("+cid+",'"+plate+"'); DECLARE @v int=SCOPE_IDENTITY(); INSERT PhieuTiepNhan(MaXe,NgayTiepNhan) VALUES(@v,SYSDATETIME()); COMMIT; SELECT @v");
  expect(vehicle).toMatch(/^\d+$/);
  await page.goto("/login");
  await page.getByLabel("Tên đăng nhập",{exact:true}).fill(config.manager.username);
  await page.getByLabel("Mật khẩu",{exact:true}).fill(config.manager.password);
  await page.getByRole("button",{name:"Đăng nhập",exact:true}).click();
  await expect(page).not.toHaveURL(/\/login$/);
  await page.goto("/admin/insurance");
  const selectVehicle=async()=>{await page.getByLabel("Tìm xe theo biển số").fill(plate);await page.getByLabel("Xe làm hồ sơ").selectOption(vehicle)};
  const form=async(title:string)=>{const f=page.locator("details").filter({has:page.locator("summary").getByText(title,{exact:true})});await f.locator("summary").click();return f};
  const save=async(f:ReturnType<typeof page.locator>,endpoint:string)=>{const response=page.waitForResponse(r=>r.request().method()==="POST"&&r.url().endsWith(endpoint));await f.getByRole("button",{name:"Lưu",exact:true}).click();expect((await response).ok()).toBeTruthy()};
  let f=await form("Thêm công ty bảo hiểm");
  await f.locator("[name=code]").fill("AP"+suffix);await f.locator("[name=name]").fill("An Phát "+suffix);await save(f,"/companies");
  await selectVehicle();
  f=await form("Thêm hợp đồng vật chất xe");await f.locator("[name=company]").selectOption({label:"An Phát "+suffix});
  for(const [key,value] of Object.entries({number:"HD"+suffix,registration:owner,certificate:owner,from:"2020-01-01",to:"2035-01-01"}))await f.locator("[name="+key+"]").fill(value);
  await save(f,"/policies");
  f=await form("Xác minh hợp đồng");await f.locator("[name=note]").fill("Đã đối chiếu đăng ký xe và giấy chứng nhận");await save(f,"/verification");
  f=await form("Mở hồ sơ tổn thất");
  for(const [key,value] of Object.entries({incidentAt:new Date(Date.now()-86400000).toISOString().slice(0,16),location:"Quận 1",cause:"Va chạm",damage:"Móp cửa xe"}))await f.locator("[name="+key+"]").fill(value);
  await save(f,"/claims");
  f=await form("Lưu chứng từ");await f.locator("[type=file]").setInputFiles({name:"bien-ban.pdf",mimeType:"application/pdf",buffer:Buffer.from("%PDF-1.7\n%%EOF")});await save(f,"/documents");
  await page.reload();await selectVehicle();await expect(page.getByRole("button",{name:"bien-ban.pdf"})).toBeVisible();
  expect(sql("SELECT COUNT(*) FROM ChungTuBaoHiem d JOIN HoSoBaoHiem h ON h.MaHoSoBaoHiem=d.MaHoSoBaoHiem JOIN PhieuTiepNhan p ON p.MaTiepNhan=h.MaTiepNhan WHERE p.MaXe="+vehicle)).toBe("1");
  const claim=(await call("GET","/insurance/claims?vehicleId="+vehicle))[0];
  const prefix="/insurance/claims/"+claim.id;
  const work=()=>call("GET",prefix+"/finance");
  for(const status of ["DA_THONG_BAO","CHO_GIAM_DINH"])await call("PUT",prefix+"/follow-up",{version:(await work()).version,status,assessor:"Nguyễn Minh An",note:"Đối chiếu hồ sơ"});
  let state=await work();await call("POST",prefix+"/assessments",{version:state.version,documentId:state.documents[0].id,damage:"Cửa trước",finding:"Sửa vỏ cửa"});
  const svc=await call("POST","/services",{name:"Kiểm tra cửa "+suffix,type:"Bảo dưỡng",unitPrice:200000});
  const repair=await call("POST","/repair-orders",{receptionId:claim.receptionId,services:[{serviceId:svc.id,quantity:1}]});
  const quote=await call("POST","/quotations",{repairOrderId:repair.order.id,lines:[{kind:"SERVICE",itemId:svc.id,quantity:1}]});
  await call("POST","/quotations/"+quote.id+"/send",{version:quote.version});
  const lineId=quote.lines[0].id;
  await call("POST",prefix+"/finance/proposals",{version:(await work()).version,quoteId:quote.id,revision:quote.revision,direct:true,lines:[{lineId,amount:180000}]});
  state=await work();
  const evidence=await request.post("/api"+prefix+"/documents",{headers:{Authorization:"Bearer "+staff.accessToken},multipart:{category:"QUYET_DINH",version:String(state.version),file:{name:"quyet-dinh.pdf",mimeType:"application/pdf",buffer:Buffer.from("%PDF-1.7\n%%EOF")}}});
  expect(evidence.ok()).toBeTruthy();state=await work();
  await call("POST",prefix+"/finance/decisions",{version:state.version,proposalId:state.proposals[0].id,documentId:state.documents.find((d:{category:string})=>d.category==="QUYET_DINH").id,reference:"QD"+suffix,reason:"Doanh nghiệp duyệt theo biên bản",lines:[{lineId,amount:150000}]});
  const client=await browser.newContext();try {
    const view=await client.newPage();await view.goto("/login");await view.getByLabel("Tên đăng nhập",{exact:true}).fill(config.customer.username);await view.getByLabel("Mật khẩu",{exact:true}).fill(config.customer.password);
    await view.getByRole("button",{name:"Đăng nhập",exact:true}).click();await expect(view).not.toHaveURL(/\/login$/);await view.goto("/customer/quotations");
    await view.getByRole("button").filter({hasText:"BG"+quote.id+" · "+plate}).click();
    await expect(view.getByText(/Phần khách dự kiến trả gara:.*50[.,]000/)).toBeVisible();
  } finally {await client.close();}
  if(process.env.GARAGE_VERIFY_SHARE)writeFileSync(process.env.GARAGE_VERIFY_SHARE,JSON.stringify({quoteId:quote.id,approved:150000,customerAmount:50000}));
});
